ITEM_RE = re.compile(r'^- \[[ x]\] \*\*(\d+[a-h]?\.\d+b?) (.*?)\*\*\s*$')
ID_TOKEN = re.compile(r'(?<![A-Za-z0-9-])(FR-[A-Z]+-\d+(?: to (?:FR-[A-Z]+-)?\d+)?|TR-\d+|R\d+(?: to R\d+)?|D\d+|OQ-\d+)(?![A-Za-z0-9-])')


def strip_ticks(s):
    return s.replace('`', '')


def parse_checklist(lines):
    """Return (sections, items). sections: key -> {heading, kind}; items: list of dicts in order."""
    sections = {}
    items = []
    current = None
    for i, line in enumerate(lines):
        m = re.match(r'^## Slice (\d+): (.*)$', line)
        if m and m.group(1) in ('0', '6'):
            current = m.group(1)
            sections[current] = {'heading': m.group(2), 'kind': 'slice'}
            continue
        m = re.match(r'^### (\d[a-h]) (.*)$', line)
        if m:
            current = m.group(1)
            sections[current] = {'heading': m.group(2), 'kind': 'sub'}
            continue
        m = ITEM_RE.match(line)
        if m:
            item = {'id': m.group(1), 'title': m.group(2), 'slice': current, 'ids': '', 'accept': '', 'line': i}
            for j in range(i + 1, min(i + 12, len(lines))):
                if lines[j].startswith('- [ ]') or lines[j].startswith('- [x]') or lines[j].startswith('#'):
                    break
                if lines[j].strip().startswith('- IDs:'):
                    item['ids'] = lines[j].strip()[len('- IDs:'):].strip()
                if lines[j].strip().startswith('- Accept:'):
                    item['accept'] = lines[j].strip()
            items.append(item)
    return sections, items


def closing_block(lines, last_item_line):
    """The bold summary lines that follow the last item of a sub-slice."""
    block = {}
    started = False
    for j in range(last_item_line + 1, len(lines)):
        line = lines[j]
        m = re.match(r'^\*\*(.*?)\*\* ?(.*)$', line)
        if m:
            started = True
            label, value = m.group(1), m.group(2)
            if label.endswith('definition of done:'):
                block['dod'] = value
            elif label == 'Tests that must pass:':
                block['tests'] = value
            elif label == 'Smoke test:':
                block['smoke'] = value
            elif label.startswith('hld.md section 12.2 items settled'):
                block['hld'] = value
        elif started and line.strip() == '':
            break
        elif started and not line.startswith('**'):
            break
        elif line.startswith('---') or line.startswith('## ') or line.startswith('### '):
            break
    return block


def item_title(it):
    t = strip_ticks(it['title'])
    t = re.sub(r'\bme reading\b', 'Claude reading', t)
    t = t.replace('I do not read it', 'Claude does not read it')
    t = t.rstrip('.')
    tag = ''
    if not t.startswith('STOP AND ASK') and not t.startswith('Commit point') and 'STOP AND ASK' in it['accept']:
        tag = ' [its Accept line contains a stop-and-ask]'
    return t + tag


def cited_ids(items):
    seen = []
    for it in items:
        for tok in ID_TOKEN.findall(it['ids']):
            if tok not in seen:
                seen.append(tok)
    return seen


def build_prompt(spec, sections, items, lines):
    key = spec['key']
    sec = dict(sections[key])
    sec['heading'] = strip_ticks(sec['heading'])
    mine = [it for it in items if it['slice'] == key]
    first, last = mine[0]['id'], mine[-1]['id']
    if key == '0':
        title = 'Slice 0: ' + sec['heading']
        opening = 'Slice 0: ' + sec['heading']
        head = 'Prompt 0: Slice 0: ' + sec['heading']
    elif key == '6':
        base = re.sub(r'\s*\(.*\)$', '', sec['heading'])
        head = 'Prompt 6: Slice 6: ' + base
        opening = 'Slice 6: ' + sec['heading']
    else:
        head = 'Prompt %s: Sub-slice %s: %s' % (key, key, sec['heading'])
        opening = 'Sub-slice %s: %s' % (key, sec['heading'])
    blk = closing_block(lines, mine[-1]['line'])
    dod = strip_ticks(blk.get('dod', ''))
    if dod.startswith('see the overall plan'):
        dod = 'see the Slice entry in plans/Overall_Implementation_plan.md section 8 and the items above.'
    body = []
    body.append('%s. Checklist items %s to %s in %s.' % (opening, first, last, CHECKLIST_REL))
    body.append('')
    body.append('Read first (read-only): ' + spec['read_first'])
    body.append('')
    body.append("Items. The Accept line of each item in the checklist is the acceptance check: quote it back in your plan and prove it with the real command and output.")
    for it in mine:
        body.append('- %s %s. IDs: %s' % (it['id'], item_title(it), it['ids']))
    body.append('')
    body.append('Requirement and decision IDs (FR, TR, R, D, OQ) cited by these items: ' + ', '.join(cited_ids(mine)) + '.')
    body.append('')
    body.append('Specific cautions:')
    body.extend(spec['cautions'])
    body.append('')
    body.append('Definition of done: ' + dod)
    body.append('Tests that must pass: ' + strip_ticks(blk.get('tests', '')))
    body.append('Smoke test: ' + strip_ticks(blk.get('smoke', '')))
    body.append('Commit point: item %s (I commit; you show git status and propose the message).' % last)
    body.append('hld.md section 12.2 items this sub-slice settles: ' + strip_ticks(blk.get('hld', '')))
    body.append('')
    body.append(RULES)
    body.append('')
    body.append(PROCEED)
    return '### %s\n\n```text\n%s\n```' % (head, '\n'.join(body))


